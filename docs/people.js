const pick = (a) => a[Math.floor(Math.random() * a.length)];
const rint = (lo, hi) => lo + Math.floor(Math.random() * (hi - lo + 1));
function weighted(items, weightOf) {
  const total = items.reduce((s, x) => s + weightOf(x), 0);
  let r = Math.random() * total;
  for (const x of items) { r -= weightOf(x); if (r <= 0) return x; }
  return items[items.length - 1];
}

const N = D.N;
const kata = () => pick(N.KATA) + pick(N.KATA_TAIL);
// 割合: ゆるい名詞・食べ物 35 / 二つ名・自虐 25 / カタカナ造語・人名もじり 20 / ネタ文 10 / 長音 5 / 英字＋数字 5
const CATEGORIES = [
  [35, [() => pick(N.SOFT), () => pick(N.FOOD) + pick(N.FOOD_TAIL), () => pick(N.TAN) + "たん"]],
  [25, [() => `${pick(N.ATEJI_SEI)} ${pick(N.WEAK_MEI)}`, () => pick(N.GODS), () => pick(N.SOUNA_ADJ) + pick(N.SOUNA_NOUN), () => pick(N.NICK_HEAD) + pick(N.NICK_TAIL)]],
  [20, [() => `${kata()}・${kata()}`, () => kata(), () => pick(N.FANTASY), () => pick(N.HUMAN) + pick(N.HUMAN_TAIL)]],
  [10, [() => pick(N.SENTENCES)]],
  [5, [() => pick(N.STRETCH) + "ー".repeat(rint(3, 5))]],
  [5, [() => pick(N.EN_WORDS) + pick([String(rint(1, 999)), "ZZ", "02", "9"])]],
];

export function randomNames(n) {
  const names = [];
  while (names.length < n) {
    const [, makers] = weighted(CATEGORIES, (c) => c[0]);
    const name = pick(makers)();
    // 書き出しが同じ名前（むにーーー と むにーーーー など）は並べない
    if (names.every((x) => x.slice(0, 2) !== name.slice(0, 2)) && [...name].length <= 10) names.push(name);
  }
  return names;
}

export function randomCast(n) {
  // 1 つの村で同じ性格タイプが重ならないよう、タイプは重みつきで「取り出していく」
  const pool = D.TYPES.slice();
  return randomNames(n).map((name) => {
    if (!pool.length) pool.push(...D.TYPES);
    const t = weighted(pool, (x) => x.weight);
    pool.splice(pool.indexOf(t), 1);
    // 腕前はそのタイプになりやすい腕前から、全体の割合（4:4:2）も効かせて選ぶ
    const skill = weighted([...new Set(t.skills)], (s) => D.SKILL_WEIGHT[s] * t.skills.filter((x) => x === s).length);
    const text = `タイプ: ${t.type}（腕前: ${skill}。${D.SKILL_TEXT[skill]}）
`
      + `話し方: ${t.speech}
打ち方: ${t.play}
役職を引いたときの癖: ${t.role}
発言の長さ: ${t.length}`;
    return { name, type: t.type, skill, text };
  });
}
